import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { chromium } = require('../frontend/node_modules/playwright-core');
const EDGE = 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';
const browser = await chromium.launch({ executablePath: EDGE, headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 980 } });
const errors = [];
page.on('pageerror', (e) => errors.push(String(e)));
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle', timeout: 120000 });
await page.waitForFunction(() => typeof window.__PV_VIEW === 'function', null, { timeout: 60000 });
await page.waitForTimeout(6000);
await page.mouse.click(600, 480);
await page.waitForTimeout(1600);
const visible = await page.locator('[data-testid="part-inspector"]').isVisible().catch(() => false);
const text = visible ? await page.locator('[data-testid="part-inspector"]').innerText() : '';
const html = visible ? await page.locator('[data-testid="part-inspector"]').innerHTML() : '';
await page.screenshot({ path: 'BEFORE_AFTER_SCREENSHOTS/after_part_inspector.png' });
console.log(JSON.stringify({ visible, text: text.slice(0, 500), errors, html: html.slice(0, 200) }));
await browser.close();
